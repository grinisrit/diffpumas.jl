"""
flux_comparison.jl - Compare PUMAS (C) and DiffPumas (Julia) flux calculations

This script:
1. Runs build/example-geometry for various parameter combinations
2. Caches C results in examples/data/flux_comparison.xml
3. Runs DiffPumas for the same parameters
4. Creates an interactive 3D plot comparing the results

The plot uses zenith angle θ (angle from vertical):
- θ = 0°  → vertical (muons from directly above)
- θ = 90° → horizontal (muons from horizon)

Geometry:
                    PRIMARY_ALTITUDE (1000m)
    ════════════════════════════════════════════════════════
                         |
                    AIR LAYER
                         |
    ──────────────────────────────────────── z = rock_thickness
                         |
                    ROCK LAYER
                         |      ╱ muon at zenith angle θ
                         |    ╱
                         |  ╱
                         |╱θ
    ─────────────────────●─────────────────── z = 0 (Detector)

Usage:
    julia --project=. examples/flux_comparison.jl [OPTIONS]

Options:
    --recompute          Force recomputation of C results (default: use cached)
    --samples N, -n N    Number of Monte Carlo samples per point (default: 10000)
"""

