function parse_commandline()
    n_samples = 10000
    recompute = false
    reload_physics = false
    energy_threshold_low = 100.0
    output_path = nothing  # Default will be set in main()
    straggling = true
    scattering = true
    
    if "--help" in ARGS || "-h" in ARGS
        println("""
        flux_comparison.jl - Compare PUMAS (C) and DiffPumas (Julia) flux calculations
        
        Usage:
            julia --project=. examples/flux_comparison.jl [OPTIONS]
        
        Options:
            --recompute          Force recomputation of C results (default: use cached)
            --reload-physics     Force recreation of physics tables
            --samples N, -n N    Number of Monte Carlo samples per point (default: 10000)
            --threshold N        Energy threshold for mode switching in GeV (default: 100.0)
                                Below threshold: STRAGGLED + MIXED scattering
                                Above threshold: MIXED energy loss, no scattering
            --no-straggling      Disable energy straggling (default: enabled)
            --no-scattering      Disable scattering (default: enabled)
            --output PATH, -o PATH
                                Output path for 3D plot HTML file
                                (default: examples/data/flux_comparison_3d.html)
            --help, -h           Show this help message
        
        Examples:
            julia --project=. examples/flux_comparison.jl
            julia --project=. examples/flux_comparison.jl --samples 50000
            julia --project=. examples/flux_comparison.jl --threshold 50.0
            julia --project=. examples/flux_comparison.jl --output my_plot.html
            julia --project=. examples/flux_comparison.jl --recompute --reload-physics
            julia --project=. examples/flux_comparison.jl --no-scattering
            julia --project=. examples/flux_comparison.jl --no-straggling --no-scattering
        """)
        exit(0)
    end
    
    i = 1
    while i <= length(ARGS)
        arg = ARGS[i]
        if arg == "--recompute"
            recompute = true
            i += 1
        elseif arg == "--reload-physics"
            reload_physics = true
            i += 1
        elseif arg == "--samples" || arg == "-n"
            if i + 1 <= length(ARGS)
                n_samples = parse(Int, ARGS[i + 1])
                i += 2
            else
                error("--samples requires a value")
            end
        elseif arg == "--threshold"
            if i + 1 <= length(ARGS)
                energy_threshold_low = parse(Float64, ARGS[i + 1])
                i += 2
            else
                error("--threshold requires a value")
            end
        elseif arg == "--output" || arg == "-o"
            if i + 1 <= length(ARGS)
                output_path = ARGS[i + 1]
                i += 2
            else
                error("--output requires a path")
            end
        elseif arg == "--no-straggling"
            straggling = false
            i += 1
        elseif arg == "--no-scattering"
            scattering = false
            i += 1
        elseif startswith(arg, "--samples=")
            n_samples = parse(Int, split(arg, "=")[2])
            i += 1
        elseif startswith(arg, "--threshold=")
            energy_threshold_low = parse(Float64, split(arg, "=")[2])
            i += 1
        elseif startswith(arg, "--output=")
            output_path = split(arg, "=", limit=2)[2]
            i += 1
        else
            error("Unknown argument: $arg (use --help for usage)")
        end
    end
    
    return n_samples, recompute, reload_physics, energy_threshold_low, output_path, straggling, scattering
end

function main()
    # Parse command line
    n_samples, recompute, reload_physics, energy_threshold_low, output_path, straggling, scattering = parse_commandline()
    
    # Set default output path if not provided
    if output_path === nothing
        output_path = joinpath(@__DIR__, "data", "flux_comparison.html")
    end
    
    println("=" ^ 60)
    println(" DiffPumas Flux Comparison - C vs Julia")
    println("=" ^ 60)
    println()
    
    if recompute
        println("Mode: Recompute all C results")
    else
        println("Mode: Use cached C results where available")
    end
    if reload_physics
        println("Mode: Force reload physics tables")
    end
    println("Monte Carlo samples: $n_samples")
    println("Energy threshold: $energy_threshold_low GeV")
    if straggling && scattering
        println("  Below threshold: STRAGGLED + MIXED scattering")
        println("  Above threshold: MIXED energy loss, no scattering")
    elseif straggling && !scattering
        println("  Below threshold: STRAGGLED (no scattering)")
        println("  Above threshold: MIXED energy loss, no scattering")
    elseif !straggling && scattering
        println("  Below threshold: CSDA + MIXED scattering")
        println("  Above threshold: MIXED energy loss, no scattering")
    else
        println("  All energies: Pure CSDA (no straggling, no scattering)")
    end
    println("Straggling: $straggling")
    println("Scattering: $scattering")
    println("Output plot: $output_path")
    println()
    
    # Check for C executable
    if !isfile(C_EXECUTABLE)
        println("WARNING: C executable not found at: $C_EXECUTABLE")
        println("Please compile PUMAS first:")
        println("  cd $(PUMAS_DIR) && mkdir -p build && cd build && cmake .. -DCMAKE_POLICY_VERSION_MINIMUM=3.5 -DPUMAS_BUILD_EXAMPLES=true && cmake --build .")
        println()
    end
    
    # Load or create physics (scattering tables computed from first principles)
    println("Loading physics tables...")
    if reload_physics && isfile(PHYSICS_DUMP)
        @info "Removing existing physics dump for reload..."
        rm(PHYSICS_DUMP)
    end
    physics = isfile(PHYSICS_DUMP) ? load_physics(PHYSICS_DUMP) : nothing
    if physics === nothing
        isfile(PHYSICS_DUMP) && rm(PHYSICS_DUMP; force=true)
        @info "Creating new physics tables..."
        physics = create_physics(MUON; n_energies=200, K_min=1e-3, K_max=1e9)
        save_physics(physics, PHYSICS_DUMP)
    end
    
    println("✓ Physics loaded")
    println()
    
    # Define parameter grid
    # Rock thickness: 0 to 800m in 50m steps
    thicknesses = collect(0.0:50.0:800.0)
    # Zenith angles: 0° (vertical) to 75° (near horizontal)
    zeniths = [0.0, 15.0, 30.0, 45.0, 60.0, 75.0]
    
    println("Parameter grid:")
    println("  Thicknesses: 0 to 800 m (step 50 m)")
    println("  Zenith angles: $(zeniths)°")
    println("  Energy: 1e-3 - 1e9 GeV")
    println("  MC samples: $n_samples")
    println()
    
    # Compute C results
    println("Computing PUMAS (C) flux values...")
    c_results = compute_c_flux_grid(thicknesses, zeniths; recompute=recompute)
    println()
    
    # Compute Julia results
    println("Computing DiffPumas (Julia) flux values...")
    julia_results = compute_julia_flux_grid(physics, thicknesses, zeniths; 
                                            n_samples=n_samples,
                                            energy_threshold_low=energy_threshold_low,
                                            straggling=straggling,
                                            scattering=scattering)
    println()
    
    # Print detailed flux table with sigma percentages and differences
    create_detailed_flux_table(c_results, julia_results)
    
    # Save detailed flux table to CSV (same directory as HTML)
    csv_path = joinpath(dirname(output_path), "flux_comparison.csv")
    save_detailed_flux_table_csv(c_results, julia_results, csv_path)
    
    # Create plot
    println()
    println("Creating interactive 3D plot...")
    plot_flux = create_comparison_plot(c_results, julia_results, 
                                       thicknesses, zeniths)
    
    # Save plot as HTML
    mkpath(dirname(output_path))
    open(output_path, "w") do io
        PlotlyJS.savefig(io, plot_flux, format="html")
    end
    @info "Saved 3D flux plot to: $output_path"
    
    # Display plot (in interactive environment)
    try
        display(plot_flux)
    catch
        # Not in interactive environment
    end
    
    println()
    println("Done!")
    println()
    println("View results:")
    println("  3D comparison: $output_path")
    println("  CSV table: $csv_path")
    println()
    
    return 0
end

