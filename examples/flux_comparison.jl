# Path to C executable and cache file
const PUMAS_DIR = joinpath(dirname(@__DIR__), "..", "pumas")
const C_EXECUTABLE = joinpath(PUMAS_DIR, "build", "example-geometry")
const CACHE_FILE = joinpath(@__DIR__, "data", "flux_comparison.xml")
const PHYSICS_DUMP = joinpath(@__DIR__, "data", "materials.pumas")

"""
    run_c_example(thickness, zenith, energy_min, energy_max)

Run the C example-geometry and parse the output flux.
Note: C code uses elevation, so we convert from zenith.
"""
function run_c_example(thickness::Float64, zenith::Float64, 
                       energy_min::Float64, energy_max::Float64)
    
    if !isfile(C_EXECUTABLE)
        @warn "C executable not found: $C_EXECUTABLE"
        return NaN, NaN
    end
    
    # Convert zenith to elevation for C code
    elevation = zenith_to_elevation(zenith)
    
    # Run the C executable from the PUMAS directory (so it finds materials.pumas)
    cmd = Cmd(`$C_EXECUTABLE $thickness $elevation $energy_min $energy_max`; dir=PUMAS_DIR)
    output = try
        read(cmd, String)
    catch e
        @warn "Failed to run C executable: $e"
        return NaN, NaN
    end
    
    # Parse output: "Flux : 4.92738E-03 \pm 1.16323E-04 m^{-2} s^{-1} sr^{-1}"
    m = match(r"Flux\s*:\s*([-+]?\d+\.?\d*[Ee][-+]?\d+)\s*\\pm\s*([-+]?\d+\.?\d*[Ee][-+]?\d+)", output)
    if m !== nothing
        flux = parse(Float64, m.captures[1])
        sigma = parse(Float64, m.captures[2])
        return flux, sigma
    else
        @warn "Failed to parse C output: $output"
        return NaN, NaN
    end
end

"""
    load_cached_results()

Load cached C results from XML file.
"""
function load_cached_results()
    results = Dict{Tuple{Float64,Float64}, Tuple{Float64,Float64}}()
    
    if !isfile(CACHE_FILE)
        return results
    end
    
    try
        content = read(CACHE_FILE, String)
        for m in eachmatch(r"<result thickness=\"([^\"]+)\" zenith=\"([^\"]+)\" flux=\"([^\"]+)\" sigma=\"([^\"]+)\"", content)
            thickness = parse(Float64, m.captures[1])
            zenith = parse(Float64, m.captures[2])
            flux = parse(Float64, m.captures[3])
            sigma = parse(Float64, m.captures[4])
            results[(thickness, zenith)] = (flux, sigma)
        end
    catch e
        @warn "Failed to load cache: $e"
    end
    
    return results
end

"""
    save_cached_results(results)

Save C results to XML cache file.
"""
function save_cached_results(results::Dict{Tuple{Float64,Float64}, Tuple{Float64,Float64}})
    mkpath(dirname(CACHE_FILE))
    
    open(CACHE_FILE, "w") do io
        println(io, "<?xml version=\"1.0\" encoding=\"UTF-8\"?>")
        println(io, "<!-- PUMAS flux comparison cache -->")
        println(io, "<!-- Generated by flux_comparison.jl -->")
        println(io, "<!-- zenith = angle from vertical (0° = vertical, 90° = horizontal) -->")
        println(io, "<flux_comparison energy_min=\"1e-3\" energy_max=\"1e9\">")
        
        for ((thickness, zenith), (flux, sigma)) in sort(collect(results))
            println(io, "  <result thickness=\"$thickness\" zenith=\"$zenith\" flux=\"$flux\" sigma=\"$sigma\"/>")
        end
        
        println(io, "</flux_comparison>")
    end
    
    @info "Saved $(length(results)) results to $CACHE_FILE"
end

"""
    compute_c_flux_grid(thicknesses, zeniths; recompute=false)

Compute C flux values for a grid of parameters.
"""
function compute_c_flux_grid(thicknesses::Vector{Float64}, 
                              zeniths::Vector{Float64};
                              recompute::Bool = false)
    
    energy_min = 1e-3
    energy_max = 1e9
    
    # Load cached results
    cached = load_cached_results()
    
    results = Dict{Tuple{Float64,Float64}, Tuple{Float64,Float64}}()
    
    n_total = length(thicknesses) * length(zeniths)
    n_done = 0
    
    for thickness in thicknesses
        for zenith in zeniths
            key = (thickness, zenith)
            n_done += 1
            
            if !recompute && haskey(cached, key)
                results[key] = cached[key]
                @info "[$n_done/$n_total] Using cached: thickness=$thickness m, θ=$(zenith)°"
            else
                @info "[$n_done/$n_total] Running C: thickness=$thickness m, θ=$(zenith)°"
                flux, sigma = run_c_example(thickness, zenith, energy_min, energy_max)
                results[key] = (flux, sigma)
            end
        end
    end
    
    # Save updated cache
    save_cached_results(results)
    
    return results
end

"""
    compute_julia_flux_grid(physics, thicknesses, zeniths; n_samples, energy_threshold_low, straggling, scattering)

Compute Julia flux values for a grid of parameters.
Matches PUMAS C geometry.c behavior when straggling=true, scattering=true:
- Below energy_threshold_low: STRAGGLED energy loss + MIXED scattering (transverse transport ON)
- Above energy_threshold_low: MIXED energy loss + DISABLED scattering

# Arguments
- `energy_threshold_low`: Energy threshold for mode switching in GeV (default: 100.0)
- `straggling`: Enable energy straggling (default: true)
- `scattering`: Enable scattering (default: true)
"""
function compute_julia_flux_grid(physics, 
                                  thicknesses::Vector{Float64}, 
                                  zeniths::Vector{Float64};
                                  n_samples::Int = 10000,
                                  energy_threshold_low::Float64 = 100.0,
                                  straggling::Bool = true,
                                  scattering::Bool = true)
    
    energy_min = 1e-3
    energy_max = 1e9
    
    results = Dict{Tuple{Float64,Float64}, Tuple{Float64,Float64}}()
    
    n_total = length(thicknesses) * length(zeniths)
    n_done = 0
    
    for thickness in thicknesses
        for zenith in zeniths
            n_done += 1
            elevation = zenith_to_elevation(zenith)
            @info "[$n_done/$n_total] Running Julia: thickness=$thickness m, θ=$(zenith)°"
            
            # Use provided straggling and scattering settings
            # compute_flux now returns (flux, sigma) with proper variance calculation
            flux, sigma = compute_flux(physics, 2650.0, thickness, elevation, 
                               energy_min, energy_max; n_samples=n_samples,
                               straggling=straggling, scattering=scattering,
                               energy_threshold_low=energy_threshold_low)
            
            results[(thickness, zenith)] = (flux, sigma)
        end
    end
    
    return results
end

"""
    create_comparison_plot(c_results, julia_results, thicknesses, zeniths)

Create interactive 3D comparison plot.
"""
function create_comparison_plot(c_results::Dict, julia_results::Dict,
                                 thicknesses::Vector{Float64}, 
                                 zeniths::Vector{Float64})
    
    n_t = length(thicknesses)
    n_z = length(zeniths)
    
    # Create matrices for surface plots
    c_flux = zeros(n_z, n_t)
    julia_flux = zeros(n_z, n_t)
    
    for (i, zen) in enumerate(zeniths)
        for (j, thick) in enumerate(thicknesses)
            key = (thick, zen)
            c_f = get(c_results, key, (NaN, NaN))[1]
            j_f = get(julia_results, key, (NaN, NaN))[1]
            
            c_flux[i, j] = c_f > 0 ? log10(c_f) : NaN
            julia_flux[i, j] = j_f > 0 ? log10(j_f) : NaN
        end
    end
    
    # Create 3D surface plot for flux comparison
    trace_c = surface(
        x = thicknesses,
        y = zeniths,
        z = c_flux,
        name = "PUMAS (C)",
        colorscale = "Blues",
        showscale = false,
        opacity = 0.8
    )
    
    trace_julia = surface(
        x = thicknesses,
        y = zeniths,
        z = julia_flux,
        name = "DiffPumas (Julia)",
        colorscale = "Oranges",
        showscale = false,
        opacity = 0.8
    )
    
    layout_flux = Layout(
        title = "Muon Flux Comparison: PUMAS (C) vs DiffPumas (Julia)",
        scene = attr(
            xaxis = attr(title = "Rock Thickness (m)"),
            yaxis = attr(title = "Zenith Angle θ (°)"),
            zaxis = attr(title = "log₁₀(Flux) [m⁻² s⁻¹ sr⁻¹]")
        ),
        width = 900,
        height = 700
    )
    
    plot_flux = Plot([trace_c, trace_julia], layout_flux)
    
    return plot_flux
end

"""
    create_comparison_table(c_results, julia_results)

Create a formatted comparison table.
"""
function create_comparison_table(c_results::Dict, julia_results::Dict)
    println()
    println("=" ^ 85)
    println("  PUMAS (C) vs DiffPumas (Julia) Flux Comparison")
    println("=" ^ 85)
    println()
    println("| Thickness (m) | Zenith θ (°) | PUMAS (C)    | DiffPumas (Julia) | Ratio  |")
    println("|---------------|--------------|--------------|-------------------|--------|")
    
    for key in sort(collect(keys(c_results)))
        thickness, zenith = key
        c_flux, _ = c_results[key]
        j_flux, _ = get(julia_results, key, (NaN, NaN))
        
        ratio = (c_flux > 0 && j_flux > 0 && isfinite(c_flux) && isfinite(j_flux)) ? 
                j_flux / c_flux : NaN
        
        @printf("| %13.0f | %12.0f | %12.5e | %17.5e | %6.2f |\n",
                thickness, zenith, c_flux, j_flux, ratio)
    end
    
    println("=" ^ 85)
end

"""
    save_detailed_flux_table_csv(c_results, julia_results, csv_path)

Save the detailed flux comparison table to a CSV file.
Includes flux values, relative errors (σ%), and difference percentages.
"""
function save_detailed_flux_table_csv(c_results::Dict, julia_results::Dict, csv_path::String)
    mkpath(dirname(csv_path))
    
    open(csv_path, "w") do io
        # Write CSV header
        println(io, "Thickness (m),Zenith θ (°),Julia Flux (m⁻²s⁻¹sr⁻¹),Julia σ (%),C Flux (m⁻²s⁻¹sr⁻¹),C σ (%),Diff (%)")
        
        # Write data rows
        for key in sort(collect(keys(c_results)))
            thickness, zenith = key
            c_flux, c_sigma = c_results[key]
            j_flux, j_sigma = get(julia_results, key, (NaN, NaN))
            
            # Calculate relative errors in percentage
            j_sigma_pct = (j_flux > 0 && isfinite(j_flux) && isfinite(j_sigma)) ? 
                          (j_sigma / j_flux) * 100.0 : NaN
            c_sigma_pct = (c_flux > 0 && isfinite(c_flux) && isfinite(c_sigma)) ? 
                          (c_sigma / c_flux) * 100.0 : NaN
            
            # Calculate difference percentage: ((Julia - C) / C) * 100
            diff_pct = (c_flux > 0 && j_flux > 0 && isfinite(c_flux) && isfinite(j_flux)) ? 
                       ((j_flux - c_flux) / c_flux) * 100.0 : NaN
            
            # Format values for CSV
            j_flux_str = isfinite(j_flux) ? string(j_flux) : "NaN"
            j_sigma_pct_str = isfinite(j_sigma_pct) ? string(j_sigma_pct) : "NaN"
            c_flux_str = isfinite(c_flux) ? string(c_flux) : "NaN"
            c_sigma_pct_str = isfinite(c_sigma_pct) ? string(c_sigma_pct) : "NaN"
            diff_pct_str = isfinite(diff_pct) ? string(diff_pct) : "NaN"
            
            println(io, "$thickness,$zenith,$j_flux_str,$j_sigma_pct_str,$c_flux_str,$c_sigma_pct_str,$diff_pct_str")
        end
    end
    
    @info "Saved detailed flux comparison table to: $csv_path"
end

